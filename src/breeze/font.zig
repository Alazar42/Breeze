// font.zig — Typography & font engine for Breeze.
// Uses user-supplied Open Sans font ("assets/fonts/Open_Sans/static/OpenSans-Regular.ttf")
// by default across the entire project for Raylib and UI rendering, unless replaced.

const std = @import("std");
const Vec2 = @import("math/vec2.zig");
pub const rl = @import("raylib");

pub const default_font_path = "assets/fonts/Open_Sans/static/OpenSans-Regular.ttf";

var global_font: ?rl.Font = null;
var global_font_loaded: bool = false;

/// Load or return the project-wide default font (Open Sans by default, unless replaced).
pub fn getDefaultFont() rl.Font {
    if (global_font) |f| return f;

    if (rl.isWindowReady()) {
        const candidate_paths = [_][:0]const u8{
            "assets/fonts/Open_Sans/static/OpenSans-Regular.ttf",
            "../assets/fonts/Open_Sans/static/OpenSans-Regular.ttf",
            "assets/fonts/Open_Sans/OpenSans-VariableFont_wdth,wght.ttf",
            "assets/fonts/Open_Sans/static/OpenSans-Bold.ttf",
        };
        for (candidate_paths) |path| {
            if (rl.loadFontEx(path, 32, null)) |font| {
                global_font = font;
                global_font_loaded = true;
                return font;
            } else |_| {}
        }
        if (rl.getFontDefault()) |def_font| {
            global_font = def_font;
            return def_font;
        } else |_| {}
    }
    return std.mem.zeroes(rl.Font);
}

/// Replace the project-wide default font with a custom font ("unless replaced").
pub fn setDefaultFont(font: rl.Font) void {
    global_font = font;
    global_font_loaded = true;
}

/// Returns true if the default Open Sans or custom font has been loaded into Raylib.
pub fn isFontLoaded() bool {
    return global_font_loaded;
}

/// Unload the default font if loaded.
pub fn unloadDefaultFont() void {
    if (global_font) |font| {
        if (global_font_loaded and rl.isWindowReady()) {
            rl.unloadFont(font);
        }
        global_font = null;
        global_font_loaded = false;
    }
}

/// Renders text using the project default font (Open Sans) with Raylib.
pub fn drawText(text: [:0]const u8, posX: i32, posY: i32, fontSize: i32, color: rl.Color) void {
    const font = getDefaultFont();
    const pos = rl.Vector2{ .x = @floatFromInt(posX), .y = @floatFromInt(posY) };
    rl.drawTextEx(font, text, pos, @floatFromInt(fontSize), 1.0, color);
}

/// Renders text with position, font size, and spacing using Open Sans.
pub fn drawTextEx(text: [:0]const u8, position: rl.Vector2, fontSize: f32, spacing: f32, tint: rl.Color) void {
    const font = getDefaultFont();
    rl.drawTextEx(font, text, position, fontSize, spacing, tint);
}

/// Measure text dimensions using the project default font (Open Sans).
pub fn measureText(text: [:0]const u8, fontSize: f32) rl.Vector2 {
    if (rl.isWindowReady()) {
        const font = getDefaultFont();
        return rl.measureTextEx(font, text, fontSize, 1.0);
    }
    const measured = Font.measureText(text, fontSize / 16.0);
    return .{ .x = measured.x, .y = measured.y };
}

pub const Font = struct {
    name: []const u8 = "OpenSans",
    glyph_width: u32 = 8,
    glyph_height: u32 = 8,

    /// Measure the pixel dimensions required to render `text` at `scale`.
    pub fn measureText(text: []const u8, scale: f32) Vec2 {
        var max_w: f32 = 0.0;
        var current_w: f32 = 0.0;
        var lines: f32 = 1.0;

        for (text) |c| {
            if (c == '\n') {
                if (current_w > max_w) max_w = current_w;
                current_w = 0.0;
                lines += 1.0;
            } else {
                current_w += 8.0 * scale;
            }
        }
        if (current_w > max_w) max_w = current_w;

        return .{
            .x = max_w,
            .y = lines * (10.0 * scale),
        };
    }

    /// Retrieve the 8x8 1bpp bitmap for an ASCII character.
    pub fn getGlyphBitmap(char: u8) [8]u8 {
        if (char < 32 or char > 126) {
            return font_8x8[0]; // fallback to space
        }
        return font_8x8[char - 32];
    }
};

